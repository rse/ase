import fs                            from "node:fs"
import os                            from "node:os"
import path                          from "node:path"
import { fileURLToPath }             from "node:url"

import YAML, { type Document }       from "yaml"
import * as v                        from "valibot"
import { parse as shParse }          from "shell-quote"

import { projectRoot, userConfigDir } from "./ase-config-scope.js"
import type { Tool }                  from "./ase-setup-common.js"

/*  the scopes of the alias files, by ascending precedence  */
export const aliasScopes = [ "user", "project" ] as const
export type AliasScope   = typeof aliasScopes[number]

/*  the content of an alias file: the full aliases (alias name to command line),
    the option aliases (skill to option alias to expansion), and the option
    defaults (skill to option tokens)  */
export type AliasData = {
    alias:   Record<string, string>
    option:  Record<string, Record<string, string>>
    default: Record<string, string>
}

/*  a single entry of the alias files, with the scope supplying it  */
export type AliasEntry = {
    kind:   "alias" | "option" | "default"
    name:   string      /*  alias name (kind "alias"), resp. skill name (kinds "option" and "default")  */
    option: string      /*  option alias (kind "option"), resp. empty  */
    value:  string      /*  command line, expansion, resp. option tokens  */
    scope:  AliasScope
}

/*  the option aliases and the option default tokens of a skill  */
export type AliasTuning = {
    options:  Record<string, string>
    defaults: string[]
}

/*  the marker of the generated shim skills of the full aliases  */
const MARKER = "generated by ase alias sync"

/*  the name patterns of aliases, skills, and option aliases  */
const aliasNameRe  = /^[a-z][a-z0-9-]{0,63}$/
const skillNameRe  = /^ase-[a-z0-9]+(?:-[a-z0-9]+)+$/
const optionNameRe = /^--[a-z][a-z0-9-]*$/

/*  the schema of an alias file  */
const aliasSchema = v.nullish(v.strictObject({
    alias: v.nullish(v.record(
        v.pipe(v.string(),
            v.regex(aliasNameRe, "invalid alias name (expected up to 64 lower-case letters, digits, and dashes)"),
            v.check((name) => !name.startsWith("ase-"), "alias name must not start with \"ase-\"")),
        v.pipe(v.string(), v.nonEmpty("empty command line")))),
    option: v.nullish(v.record(
        v.pipe(v.string(), v.regex(skillNameRe, "invalid skill name")),
        v.nullish(v.record(
            v.pipe(v.string(), v.regex(optionNameRe, "invalid option alias (expected \"--<name>\")")),
            v.pipe(v.string(), v.nonEmpty("empty option alias expansion")))))),
    default: v.nullish(v.record(
        v.pipe(v.string(), v.regex(skillNameRe, "invalid skill name")),
        v.string()))
}))

/*  split a command line into its tokens, honoring the quoting and escaping
    (but neither expanding variables nor interpreting shell operators)  */
export const splitArgs = (text: string): string[] =>
    shParse(text, (key) => `$${key}`)
        .flatMap((e) => typeof e === "string" ? [ e ] :
            "pattern" in e ? [ e.pattern ] :
                "op" in e ? [ e.op ] :
                    `#${e.comment}`.split(/\s+/).filter((s) => s.length > 0))

/*  join tokens into a command line, quoting only the tokens which need it  */
export const joinArgs = (tokens: string[]): string =>
    tokens.map((token) => /^[^\s"'\\$`#]+$/.test(token) ? token : `'${token.replace(/'/g, "'\\''")}'`).join(" ")

/*  determine the command name of the first token of a command line, i.e., the token
    without its leading "/" (resp. "$" of OpenAI Codex CLI) and its "ase:" plugin prefix  */
export const commandName = (token: string): string =>
    token.replace(/^[/$]/, "").replace(/^ase:/, "")

/*  read a text file, or null if it does not exist  */
const readText = (file: string): string | null => {
    try {
        return fs.readFileSync(file, "utf8")
    }
    catch (err: unknown) {
        const code = (err as NodeJS.ErrnoException).code
        if (code === "ENOENT" || code === "ENOTDIR")
            return null
        throw err
    }
}

/*  the alias file of a scope, or null for the project scope outside of a project  */
export const aliasFile = (scope: AliasScope): string | null => {
    if (scope === "user")
        return path.join(userConfigDir(), "aliases.yaml")
    const root = projectRoot()
    return root !== null ? path.join(root, ".ase", "aliases.yaml") : null
}

/*  the directory of the shim skills of a scope and an agent tool
    (or null for the project scope outside of a project)  */
const shimDir = (scope: AliasScope, tool: Tool): string | null => {
    const base = scope === "user" ? os.homedir() : projectRoot()
    if (base === null)
        return null
    return path.join(base, tool === "claude" ? ".claude" : ".agents", "skills")
}

/*  parse and validate the text of an alias file  */
const parseAliasData = (text: string, file: string): AliasData => {
    let data: unknown
    try {
        data = YAML.parse(text)
    }
    catch (err: unknown) {
        throw new Error(`alias: cannot parse "${file}": ${err instanceof Error ? err.message : String(err)}`, { cause: err })
    }
    const result = v.safeParse(aliasSchema, data)
    if (!result.success) {
        const issue = result.issues[0]
        const where = v.getDotPath(issue)
        throw new Error(`alias: invalid "${file}"${where !== null ? ` at "${where}"` : ""}: ${issue.message}`)
    }
    const out    = result.output ?? {}
    const option = Object.fromEntries(Object.entries(out.option ?? {}).map(([ skill, opts ]) => [ skill, { ...opts } ]))
    return { alias: { ...out.alias }, option, default: { ...out.default } }
}

/*  the bundled ASE skills (see the "build-plugin" build step), or null if not bundled  */
const skillsDir = (): string =>
    path.join(path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."), "plugin", "skills")
export const bundledSkills = (): string[] | null => {
    try {
        return fs.readdirSync(skillsDir()).filter((entry) => skillNameRe.test(entry))
    }
    catch {
        return null
    }
}

/*  the options specification of a bundled ASE skill (the second argument of the
    expansion of its "getopt" definition), or null if not determinable  */
export const skillSpec = (skill: string): string | null => {
    const md = readText(path.join(skillsDir(), skill, "SKILL.md"))
    const m  = md !== null ? /<expand\s+name="getopt"\s+arg1="([^"]*)"\s+arg2="([^"]*)"/.exec(md) : null
    return m !== null && m[1] === skill ? m[2] : null
}

/*  the argument hint of a bundled ASE skill (the "argument-hint" of its frontmatter), or empty  */
const skillHint = (skill: string): string => {
    const md = readText(path.join(skillsDir(), skill, "SKILL.md"))
    const m  = md !== null ? /^---\r?\n([\s\S]*?)\r?\n---/.exec(md) : null
    if (m === null)
        return ""
    const front = YAML.parse(m[1]) as Record<string, unknown> | null
    const hint  = front?.["argument-hint"]
    return typeof hint === "string" ? hint : ""
}

/*  write a file, but only if its content changed, and report the change  */
const writeChanged = (file: string, text: string): string[] => {
    if (readText(file) === text)
        return []
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, text, "utf8")
    return [ `wrote "${file}"` ]
}

/*  the full aliases, option aliases, and option defaults of the alias files of the
    user and the project, where an entry of the project overrides one of the user  */
export class Aliases {
    private constructor (
        private files: Record<AliasScope, { file: string, data: AliasData } | null>
    ) {}

    /*  load the alias files of both scopes  */
    static load (): Aliases {
        const files = { user: null, project: null } as Record<AliasScope, { file: string, data: AliasData } | null>
        for (const scope of aliasScopes) {
            const file = aliasFile(scope)
            if (file !== null)
                files[scope] = { file, data: parseAliasData(readText(file) ?? "", file) }
        }
        return new Aliases(files)
    }

    /*  modify the alias file of a scope through its YAML document (keeping its comments),
        then check the reloaded aliases and synchronize the shim skills of the scope for
        the agent tool, where the previous alias file is restored on any failure; returns
        the changes  */
    static modify (scope: AliasScope, tool: Tool, modify: (doc: Document) => void, check: (aliases: Aliases) => void = () => {}): string[] {
        const file = aliasFile(scope)
        if (file === null)
            throw new Error("alias: no project context for the scope \"project\"")
        const prev = readText(file)
        const doc  = YAML.parseDocument(prev ?? "")
        if (doc.errors.length > 0)
            throw new Error(`alias: cannot parse "${file}": ${doc.errors[0].message}`)
        modify(doc)
        const prune = (keys: unknown[]) => {
            const node = doc.getIn(keys)
            if (YAML.isMap(node) && node.items.length === 0)
                doc.deleteIn(keys)
        }
        const options = doc.getIn([ "option" ])
        if (YAML.isMap(options))
            for (const item of [ ...options.items ])
                prune([ "option", YAML.isScalar(item.key) ? item.key.value : item.key ])
        for (const section of [ "alias", "option", "default" ])
            prune([ section ])
        fs.mkdirSync(path.dirname(file), { recursive: true })
        fs.writeFileSync(file, doc.toString({ indent: 4 }), "utf8")
        try {
            const aliases = Aliases.load()
            check(aliases)
            return aliases.sync(scope, tool)
        }
        catch (err: unknown) {
            if (prev !== null)
                fs.writeFileSync(file, prev, "utf8")
            else
                fs.rmSync(file, { force: true })
            throw err
        }
    }

    /*  the alias file of a scope, or null for the project scope outside of a project  */
    file (scope: AliasScope): string | null {
        return this.files[scope]?.file ?? null
    }

    /*  the effective entries of both scopes (or of a single scope only)  */
    entries (only?: AliasScope): AliasEntry[] {
        const entries = new Map<string, AliasEntry>()
        for (const scope of aliasScopes) {
            const data = this.files[scope]?.data
            if (data === undefined || (only !== undefined && scope !== only))
                continue
            for (const [ name, value ] of Object.entries(data.alias))
                entries.set(`alias:${name}`, { kind: "alias", name, option: "", value, scope })
            for (const [ name, options ] of Object.entries(data.option))
                for (const [ option, value ] of Object.entries(options))
                    entries.set(`option:${name}:${option}`, { kind: "option", name, option, value, scope })
            for (const [ name, value ] of Object.entries(data.default))
                entries.set(`default:${name}`, { kind: "default", name, option: "", value, scope })
        }
        return [ ...entries.values() ]
    }

    /*  the effective option aliases and option default tokens of a skill  */
    tuning (skill: string): AliasTuning {
        const tuning: AliasTuning = { options: {}, defaults: [] }
        for (const entry of this.entries().filter((entry) => entry.name === skill)) {
            if (entry.kind === "option")
                tuning.options[entry.option] = entry.value
            else if (entry.kind === "default")
                tuning.defaults = splitArgs(entry.value)
        }
        return tuning
    }

    /*  the skills with option aliases or option defaults  */
    tuned (): string[] {
        return [ ...new Set(this.entries().filter((entry) => entry.kind !== "alias").map((entry) => entry.name)) ].sort()
    }

    /*  resolve a full alias (chain), of both scopes or of a single scope only, into its
        final ASE skill and its prefix tokens, where each alias of the chain appends its
        options and fixed arguments to the ones of the alias (or skill) it targets  */
    resolve (name: string, only?: AliasScope): { skill: string, tokens: string[] } {
        const aliases = new Map(this.entries(only).filter((entry) => entry.kind === "alias")
            .map((entry) => [ entry.name, entry.value ]))
        const skills  = bundledSkills()
        const walk = (name: string, chain: string[]): { skill: string, tokens: string[] } => {
            if (chain.includes(name))
                throw new Error(`alias: cyclic alias chain "${[ ...chain, name ].join(" -> ")}"`)
            const [ head = "", ...tokens ] = splitArgs(aliases.get(name)!)
            const target = commandName(head)
            if (aliases.has(target)) {
                const resolved = walk(target, [ ...chain, name ])
                return { skill: resolved.skill, tokens: [ ...resolved.tokens, ...tokens ] }
            }
            if (!skillNameRe.test(target) || (skills !== null && !skills.includes(target)))
                throw new Error(`alias "${name}": unknown target "${head}" (expected an ASE skill or another alias` +
                    `${only !== undefined ? ` of the scope "${only}"` : ""})`)
            return { skill: target, tokens }
        }
        if (!aliases.has(name))
            throw new Error(`alias: unknown alias "${name}"`)
        return walk(name, [])
    }

    /*  render the shim skill of a full alias of a scope, which just forwards to its target  */
    private shim (name: string, scope: AliasScope): string {
        const { skill, tokens } = this.resolve(name, scope)
        const prefix  = joinArgs(tokens)
        const command = `/${skill}${prefix !== "" ? ` ${prefix}` : ""}`
        const hint    = skillHint(skill)
        const front   = YAML.stringify({
            name,
            "description":              `Alias of "${command}".`,
            ...(hint !== "" ? { "argument-hint": hint } : {}),
            "user-invocable":           true,
            "disable-model-invocation": true
        }, { lineWidth: 0 })
        const file = scope === "user" ? "the user alias file" : "\".ase/aliases.yaml\""
        return `---\n${front}---\n\n` +
            `<!-- ${MARKER} (${scope}) -- do not edit, edit ${file} instead -->\n\n` +
            `This skill is an *alias* of the ASE skill \`${skill}\`. Immediately invoke the skill\n` +
            `\`ase:${skill}\` with the arguments \`${prefix !== "" ? `${prefix} ` : ""}$ARGUMENTS\` -- the arguments\n` +
            "of the alias followed by the arguments given to this skill -- passed verbatim, and do\n" +
            "nothing else.\n"
    }

    /*  synchronize the shim skills of the full aliases of a scope for an agent tool: write
        the shims of all aliases of the scope (where the shims of the user resp. the project
        resolve their alias chains within their scope only) and remove the orphaned shims of
        the scope, leaving the shims of the other agent tools untouched; returns the changes  */
    sync (scope: AliasScope, tool: Tool): string[] {
        const dir  = shimDir(scope, tool)
        const data = this.files[scope]?.data
        if (dir === null || data === undefined)
            return []
        const marker = `${MARKER} (${scope})`

        /*  render all shims and check for skills of the same name first,
            so a failure leaves all shims untouched  */
        const shims = new Map(Object.keys(data.alias).map((name) => [ name, this.shim(name, scope) ]))
        for (const name of shims.keys()) {
            const target = path.join(dir, name)
            const md     = readText(path.join(target, "SKILL.md"))
            if (fs.existsSync(target) && (md === null || !md.includes(MARKER)))
                throw new Error(`alias "${name}": collides with the existing skill "${target}"`)
        }

        /*  write the shims and remove the orphaned ones of the scope  */
        const changes: string[] = []
        for (const [ name, shim ] of shims) {
            changes.push(...writeChanged(path.join(dir, name, "SKILL.md"), shim))
            if (tool !== "claude")
                changes.push(...writeChanged(path.join(dir, name, "agents", "openai.yaml"),
                    `#   ${marker}\npolicy:\n    allow_implicit_invocation: false\n`))
        }
        let entries: string[] = []
        try {
            entries = fs.readdirSync(dir)
        }
        catch {
            /*  no skills directory at all  */
        }
        for (const entry of entries.filter((entry) => !shims.has(entry))) {
            const target = path.join(dir, entry)
            if (readText(path.join(target, "SKILL.md"))?.includes(marker) === true) {
                fs.rmSync(target, { recursive: true, force: true })
                changes.push(`removed "${target}"`)
            }
        }
        return changes
    }
}
